import assert from 'node:assert/strict';import React from 'react';import {act,create} from 'react-test-renderer';
import {ActionListEditor} from '../packages/ui/src/ActionListEditor';
const initial='买牛奶 (due: 周六, owner: 我)\n买咖啡豆（不要深烘）\n先确认灯座，再买灯泡（没确认就不买） (owner: 朋友)\n[x] 已买糖 (due: 周日, owner: 她)';
const text=(n:any):string=>typeof n==='string'?n:(n?.children??[]).map(text).join('');
let tree:any,value=initial;const updates:string[]=[],pending:number[]=[];
const render=(v=value)=><ActionListEditor value={v} disabled={false} onChange={next=>{value=next;updates.push(next);}} onCalendarPending={delta=>pending.push(delta)}/>;
act(()=>{tree=create(render());});
const button=(label:string)=>tree.root.findAllByType('button').find((n:any)=>text(n)===label);
const input=(label:string)=>tree.root.findAllByType('input').find((n:any)=>n.props['aria-label']===label);
const open=()=>act(()=>button('设置共同时间与负责人').props.onClick());
open();assert.equal(input('共同时间说明').props.value,'周六');assert.equal(input('共同负责人').props.value,'','conflicting existing owners are not guessed');
act(()=>input('共同负责人').props.onChange({target:{value:'我'}}));assert.equal(value,initial,'typing a common draft never persists rows');
assert.match(text(tree.toJSON()),/将修改 2 条事项/);
act(()=>button('补充空白字段').props.onClick());
assert.equal(updates.length,1);assert.deepEqual(pending,[1,-1]);
assert.equal(value.split('\n')[0],initial.split('\n')[0],'unchanged existing row remains byte-for-byte');
assert.equal(value.split('\n')[1],'买咖啡豆（不要深烘） (due: 周六, owner: 我)');
assert.equal(value.split('\n')[2],'先确认灯座，再买灯泡（没确认就不买） (owner: 朋友, due: 周六)');
assert.equal(value.split('\n')[3],initial.split('\n')[3],'completed history untouched');
open();act(()=>input('共同时间说明').props.onChange({target:{value:'周日'}}));
assert.equal(button('补充空白字段').props.disabled,true,'existing dates are not overwritten by default');
act(()=>input('同时替换已有时间或负责人').props.onChange({target:{checked:true}}));
assert.match(text(tree.toJSON()),/3 条已有设置会被替换/);
act(()=>button('应用到全部未完成事项').props.onClick());
assert.ok(value.split('\n').slice(0,3).every(row=>row.includes('due: 周日')));assert.ok(value.includes('owner: 朋友'));
const applied=value;open();act(()=>input('共同负责人').props.onChange({target:{value:'临时名字'}}));
act(()=>tree.root.findByType('dialog').props.onCancel({preventDefault(){}}));assert.equal(value,applied);assert.equal(updates.length,2);
open();act(()=>tree.update(render('另一组第一项\n另一组第二项')));assert.match(text(tree.toJSON()),/清单内容已变化/);
assert.equal(button('补充空白字段').props.disabled,true);act(()=>button('取消').props.onClick());
assert.equal(pending.reduce((sum,n)=>sum+n,0),0,'shared edit owns and releases the existing unsaved guard');
act(()=>tree.unmount());
console.log('PASS common metadata ordinary UI: unique-value prefill, no owner/date guessing, blank-only preserves overrides, explicit replacement preview, completed/conditional text retained, cancel and stale context, balanced unsaved guard.');
