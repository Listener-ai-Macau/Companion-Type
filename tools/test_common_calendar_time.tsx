import assert from 'node:assert/strict';import React from 'react';import {act,create} from 'react-test-renderer';
import {ActionListEditor} from '../packages/ui/src/ActionListEditor';
const original='买牛奶 (due: 周六)\n买咖啡豆（不要深烘） (due: 周六)\n确认后买灯泡（没确认就不买） (due: 周六)\n[x] 已完成的旧事项 (due: 周日)';
const text=(n:any):string=>typeof n==='string'?n:(n?.children??[]).map(text).join('');
let tree:any,value=original;const changed:string[]=[],pending:number[]=[];
const props=()=>({value,disabled:false,onChange:(next:string)=>{value=next;changed.push(next);},onCalendarPending:(delta:1|-1)=>pending.push(delta)});
act(()=>{tree=create(<ActionListEditor {...props()}/>);});
const button=(label:string)=>tree.root.findAllByType('button').find((n:any)=>text(n)===label);
const input=(label:string)=>tree.root.findAllByType('input').find((n:any)=>n.props['aria-label']===label);
act(()=>button('设置共同时间与负责人').props.onClick());
act(()=>button('确认共同日历日期').props.onClick());
assert.equal(tree.root.findAllByType('dialog').length,2);
assert.equal(input('共同时间 日历日期').props.value,'','relative wording never supplies a date');
assert.equal(input('共同时间 指定时刻').props.checked,false,'no arbitrary hour is introduced for a common relative day');
let stopped=false;
act(()=>tree.root.findByProps({'aria-label':'共同时间 日历时间'}).props.onCancel({preventDefault(){},stopPropagation(){stopped=true;}}));
assert.equal(stopped,true);assert.equal(tree.root.findAllByType('dialog').length,1,'cancel date only, retain common-field draft');
assert.equal(value,original);assert.equal(pending.reduce((a,b)=>a+b,0),1);
act(()=>button('确认共同日历日期').props.onClick());
act(()=>input('共同时间 日历日期').props.onChange({target:{value:'2026-10-31'}}));
act(()=>input('共同时间 指定时刻').props.onChange({target:{checked:true}}));
assert.equal(button('使用此日历时间').props.disabled,true,'time must be explicitly entered');
act(()=>input('共同时间 日历时刻').props.onChange({target:{value:'09:30'}}));
act(()=>tree.root.findByProps({'aria-label':'共同时间 日历时区'}).props.onChange({target:{value:'offset'}}));
act(()=>input('共同时间 UTC 偏移').props.onChange({target:{value:'+08:00'}}));
act(()=>button('使用此日历时间').props.onClick());
assert.equal(value,original,'confirming date changes only the common draft');
assert.equal(tree.root.findAllByType('dialog').length,1);
assert.match(text(tree.toJSON()),/2026年10月31日 09:30/);
assert.equal(button('补充空白字段').props.disabled,true,'existing dates are protected until replacement is explicitly selected');
act(()=>input('同时替换已有时间或负责人').props.onChange({target:{checked:true}}));
assert.match(text(tree.toJSON()),/将修改 3 条事项/);
act(()=>button('应用到全部未完成事项').props.onClick());
assert.equal(changed.length,1);assert.equal(pending.reduce((a,b)=>a+b,0),0);
assert.ok(value.split('\n').slice(0,3).every(row=>row.includes('due: 2026-10-31T09:30:00+08:00')));
assert.equal(value.split('\n')[3],original.split('\n')[3]);assert.match(value,/不要深烘/);assert.match(value,/没确认就不买/);
act(()=>tree.unmount());
console.log('PASS one explicit common calendar confirmation, nested cancel and draft guards, original relative date not guessed, replacement review, conditions/completed history preserved.');
