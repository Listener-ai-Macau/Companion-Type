const assert=require('node:assert/strict'),vm=require('node:vm'),{buildSync}=require('esbuild');
const code=buildSync({entryPoints:['packages/ui/src/recordingPresentation.ts'],bundle:true,write:false,platform:'node',format:'cjs',tsconfig:'apps/windows/tsconfig.json'}).outputFiles[0].text;
const context={module:{exports:{}},exports:{},require};context.exports=context.module.exports;vm.runInNewContext(code,context);
const {recordingDisplayTitle:title,recordingDateGroup:group,recordingTextState:state}=context.module.exports;
const base={title:'设备录音 #408',deviceRecordingId:408,source:'boardDevice',status:'captured',startedAt:'2026-11-12T12:05:00Z',transcriptText:'',transcriptFinal:false,processingPolicy:'manual',audioStored:true,retention:{audioCached:true},recovery:{stage:'idle'}};
const before=JSON.stringify(base);
assert.equal(title({...base,title:'我的名字 #408'}),'我的名字 #408');
assert(!title(base).includes('#408'));assert(title(base).includes('11月12日'));
assert.equal(title({...base,transcriptText:'这一句还没有识别完'}),title(base),'Never present an unfinished partial as the recording name');
assert.equal(title({...base,transcriptFinal:true,transcriptText:'是\n过来吧\n周五核对演示内容。'}),title(base),'Recognition and its revisions must not silently rename a saved recording');
assert.equal(title({...base,title:'设备录音'}),title(base),'Ordinary recorder title must be distinguishable by its saved recording time');
assert.equal(title({...base,title:'会议录音'}),title(base));
assert.equal(title({...base,startedAt:'invalid'}),'卡片录音 408');
assert.equal(group(base,new Date('2026-11-12T12:06:00Z')),'今天');
assert.equal(group(base,new Date('2026-11-13T12:06:00Z')),'昨天');
assert.equal(state(base).label,'可回听');
assert.equal(state({...base,processingPolicy:'localTranscription'},{automatic:false,localReady:true}).label,'可手动转文字');
assert.equal(state({...base,processingPolicy:'localTranscription'},{automatic:true,localReady:false}).label,'需准备本机转写');
assert.equal(state({...base,processingPolicy:'localTranscription'},{automatic:true,localReady:true}).label,'等待转文字');
assert.equal(state({...base,recovery:{stage:'transcribing'}}).label,'正在转文字');
assert.equal(state({...base,recovery:{stage:'paused',lastError:'failure'}}).label,'文字未生成');
assert.equal(state({...base,pendingReason:'needs_segments'}).label,'音频待收齐');
assert.equal(state({...base,transcriptFinal:true,transcriptText:'完成文字'}),null);
assert.equal(JSON.stringify(base),before,'No presentation helper may alter the saved record');
console.log('PASS recording identity and saved-state presentation without mutating source data.');
